export function Sidebar({ user, onNavigate }: SidebarProps) {
  const location = useLocation();
  const navItems = getNavItems(user.role);

  const isActive = (path: string) => location.pathname === path;

  return (
    <aside className="flex h-full flex-col bg-white">
      {/* Logo */}
      <div className="flex h-16 items-center px-6">
        <Link to="/" className="flex items-center gap-2.5" onClick={onNavigate}>
          <img src="/logo-mealbridge.png" alt="MealBridge" className="h-10 object-contain" />
        </Link>
      </div>

      {/* Navigation */}
      <nav className="flex-1 space-y-1 px-3 py-4">
        {navItems.map((item) => {
          const active = isActive(item.path);
          return (
            <Link
              key={item.path}
              to={item.path}
              onClick={onNavigate}
              className={`flex items-center gap-3 rounded-lg px-3 py-2.5 text-sm font-medium transition-colors ${
                active
                  ? "bg-green-50 text-green-700"
                  : "text-gray-600 hover:bg-gray-50 hover:text-gray-900"
              }`}
            >
              <span className={active ? "text-green-600" : "text-gray-400"}>
                {iconMap[item.icon] || iconMap.dashboard}
              </span>
              {item.label}
            </Link>
          );
        })}
      </nav>
    </aside>
  );
}
